#include "webscene_precompiled_javascript.h"
#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>

namespace {
std::string cpp_string(const char* text)
{
    // Byte escapes avoid quote/newline/path injection into generated C++.
    std::ostringstream out;
    out << '"' << std::oct << std::setfill('0');
    for (const auto* p = reinterpret_cast<const unsigned char*>(text); *p; ++p)
        out << '\\' << std::setw(3) << unsigned(*p);
    out << '"';
    return out.str();
}
void byte_list(std::ostream& out, const uint8_t* data, size_t size)
{
    for (size_t i = 0; i < size; ++i) {
        if (i % 24 == 0) out << '\n';
        out << unsigned(data[i]) << ',';
    }
}
int write_cpp(const webscene_precompiled_javascript_v1* entry, void* user)
{
    auto& out = *static_cast<std::ostream*>(user);
    out << "// Generated by the matching WebScene V8 compiler. Do not edit.\n"
           "#include <webscene_precompiled_javascript.h>\n#include <cstdio>\n#include <cstdlib>\n"
           "namespace {\nconst uint8_t cache[] = {";
    byte_list(out, entry->data, entry->data_length);
    out << "\n};\nconst webscene_precompiled_javascript_v1 entry = {\n"
           "sizeof(webscene_precompiled_javascript_v1),1," << entry->is_module << ','
        << entry->cached_data_version_tag << ",{";
    byte_list(out, entry->source_sha256, 32);
    out << "\n},{";
    byte_list(out, entry->payload_sha256, 32);
    out << "\n}," << cpp_string(entry->v8_version) << ','
        << cpp_string(entry->snapshot_fingerprint) << ",cache,sizeof(cache)};\n"
           "struct install { install() {\n"
           "if(webscene_register_precompiled_javascript_v1(&entry)!=0) {\n"
           "std::fputs(\"Invalid/conflicting packaged JavaScript cache\\n\",stderr); std::abort();\n"
           "}} }; const install registered;\n}\n";
    return out ? 0 : -1;
}
}
int main(int argc, char** argv)
{
    try {
        std::string input, output, name, kind = "classic";
        for (int i = 1; i < argc; ++i) {
            const std::string arg = argv[i];
            if (arg == "--help") {
                std::cout << "webscene-jsc --input FILE --output FILE.cpp [--kind classic|module] [--name NAME]\n";
                return 0;
            }
            if (i + 1 >= argc) throw std::runtime_error("Missing value for " + arg);
            auto value = std::string(argv[++i]);
            if (arg == "--input") input = value;
            else if (arg == "--output") output = value;
            else if (arg == "--name") name = value;
            else if (arg == "--kind") kind = value;
            else throw std::runtime_error("Unknown argument: " + arg);
        }
        if (input.empty() || output.empty() || (kind != "classic" && kind != "module"))
            throw std::runtime_error("Use --input FILE --output FILE.cpp --kind classic|module");
        const auto in_path = std::filesystem::u8path(input);
        const auto out_path = std::filesystem::u8path(output);
        if (std::filesystem::weakly_canonical(in_path) == std::filesystem::weakly_canonical(out_path))
            throw std::runtime_error("Output must not overwrite JavaScript source");
        const auto size = std::filesystem::file_size(in_path);
        if (size > 32U * 1024U * 1024U) throw std::runtime_error("Source exceeds 32 MiB");
        std::ifstream stream(in_path, std::ios::binary);
        if (!stream) throw std::runtime_error("Unable to open " + input);
        std::string source(static_cast<size_t>(size), '\0');
        if (!stream.read(source.data(), static_cast<std::streamsize>(size)))
            throw std::runtime_error("Unable to read " + input);
        if (name.empty()) name = input;
        // Build to memory; compilation errors cannot leave a valid-looking output.
        std::ostringstream generated;
        char error[4096]{};
        if (webscene_precompile_javascript_v1(source.data(), source.size(), name.c_str(),
                kind == "module", write_cpp, &generated, error, sizeof(error)) != 0)
            throw std::runtime_error(error);
        if (out_path.has_parent_path()) std::filesystem::create_directories(out_path.parent_path());
        std::ofstream target(out_path, std::ios::binary | std::ios::trunc);
        const auto contents = generated.str();
        target.write(contents.data(), static_cast<std::streamsize>(contents.size()));
        target.close();
        if (!target) {
            std::error_code ignored;
            std::filesystem::remove(out_path, ignored);
            throw std::runtime_error("Unable to write " + output);
        }
        std::cout << "Precompiled " << kind << " " << input << " (" << size << " source bytes)\n";
        return 0;
    } catch (const std::exception& e) {
        std::cerr << "webscene-jsc: " << e.what() << '\n';
        return 1;
    }
}
